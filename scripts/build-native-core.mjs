// Build the native core: the shared Studio engines as one script a native host
// evaluates offline (the iOS App's JavaScriptCore bridge, apps/ios/).
//
// Outputs (default studio/native-build/, gitignored like studio/web-build/):
//
//   mml-core.js       one classic script. It installs `globalThis.MMLNativeCore`
//                     (studio/native/core-facade.mjs) over the same modules the
//                     MCP technical tools run: application/technical-service.mjs,
//                     application/provenance.mjs, mml/parser.mjs, rules/, and
//                     dist/core.js. The Git-backed Canonical loader is replaced
//                     by the static runtime package Studio Web ships, rendered
//                     by the same helper, so both hosts carry the same bytes and
//                     digest for one Published Canonical release.
//   mml-core.json     the bundle's manifest: its SHA-256, the Canonical release
//                     and runtime package digest it carries, every source module
//                     compiled into it with that module's SHA-256, and, as audit
//                     only, the Git provenance of this build.
//   conformance.json  every case in studio/native/conformance-cases.mjs with the
//                     answer the Node server path gives it (the technical service
//                     over the Git-loaded Canonical gate, as server/mcp.mjs
//                     composes it). Host tests require the bundle to reproduce
//                     these answers exactly.
//
// The bundle is reproducible: its bytes depend on the sources, the Canonical
// release and the pinned bundler, never on Git history, time or the machine.
// Git provenance lives only in the manifest's `audit`, as it lives only in
// Studio Web's build.json.
//
// The build fails closed: a Node API, a bare package specifier or an unexpected
// bundler warning anywhere in the graph stops it, because the host that
// evaluates the result has none of them.
import { build as esbuild, version as esbuildVersion } from 'esbuild';
import { createHash } from 'node:crypto';
import { realpathSync } from 'node:fs';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadPublishedCanonical } from '../studio/backend/bootstrap/index.mjs';
import { SUPPORTED_CANONICAL_VERSIONS } from '../studio/backend/rules/supported-releases.mjs';
import { NATIVE_CONFORMANCE_CASES } from '../studio/native/conformance-cases.mjs';
import { canonicalRuntimePackage } from './canonical-runtime-package.mjs';

const repositoryRoot = fileURLToPath(new URL('../', import.meta.url));
const sha256 = value => createHash('sha256').update(value).digest('hex');

export const NATIVE_CORE_ENTRY = 'studio/native/entry.mjs';
export const NATIVE_CORE_FILES = Object.freeze({ bundle: 'mml-core.js', manifest: 'mml-core.json', conformance: 'conformance.json' });
export const NATIVE_CORE_MANIFEST_FORMAT = 'mml-tools/native-core-manifest@1';
export const NATIVE_CORE_CONFORMANCE_FORMAT = 'mml-tools/native-core-conformance@1';
// iOS 17's JavaScriptCore, the App's minimum. The bundler lowers any newer
// syntax for it and refuses what it cannot lower.
export const NATIVE_CORE_TARGET = 'safari17';

const BANNER = '/*! mml-tools native core. Generated by scripts/build-native-core.mjs from this repository (MIT, see LICENSE); do not edit. It defines no Canonical rule: it carries the Published Canonical runtime package named in mml-core.json and the implementations that the Manifest designates. */';

// Bundler warnings that are understood. application/provenance.mjs imports the
// server's full engine set through computed paths; the native gate supplies its
// own loader, so those imports are never reached here and stay unbundled.
const EXPECTED_WARNINGS = Object.freeze([
  { id: 'unsupported-dynamic-import', file: 'studio/backend/application/provenance.mjs' },
]);

function nativeHostPlugin({ root, runtimePackage }) {
  const bootstrapPath = resolve(root, 'studio/backend/bootstrap/index.mjs');
  return {
    name: 'mml-native-host',
    setup(build) {
      build.onResolve({ filter: /^mml-native:build$/ }, () => ({ path: 'build', namespace: 'mml-native' }));
      build.onResolve({ filter: /^node:/ }, args => ({ errors: [{ text: `${args.path} is a Node API, and the native core runs in a bare JavaScript engine (imported by ${args.importer})` }] }));
      build.onResolve({ filter: /\/bootstrap\/index\.mjs$/ }, args => (
        resolve(args.resolveDir, args.path) === bootstrapPath ? { path: 'canonical-bootstrap', namespace: 'mml-native' } : undefined
      ));
      build.onResolve({ filter: /^[^./]/ }, args => ({ errors: [{ text: `Bare specifier ${args.path} cannot be resolved by a native host (imported by ${args.importer})` }] }));
      build.onLoad({ filter: /.*/, namespace: 'mml-native' }, args => ({
        contents: args.path === 'build'
          ? `export const NATIVE_BUILD = Object.freeze({ canonicalDigest: '${runtimePackage.digest}' });\n`
          : runtimePackage.bootstrapModule,
        loader: 'js',
        resolveDir: root,
      }));
    },
  };
}

// The bundle and its manifest, without writing anything.
export async function buildNativeCoreBundle({ root = repositoryRoot, canonical }) {
  const runtimePackage = canonicalRuntimePackage(canonical);
  const result = await esbuild({
    absWorkingDir: root,
    entryPoints: [NATIVE_CORE_ENTRY],
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'neutral',
    target: [NATIVE_CORE_TARGET],
    charset: 'utf8',
    legalComments: 'inline',
    minify: false,
    sourcemap: false,
    metafile: true,
    logLevel: 'silent',
    banner: { js: BANNER },
    plugins: [nativeHostPlugin({ root, runtimePackage })],
  });
  const unexpected = result.warnings.filter(warning => !EXPECTED_WARNINGS.some(expected => warning.id === expected.id && warning.location?.file === expected.file));
  if (unexpected.length) {
    throw Error(`Native core build refused unexpected bundler warnings:\n${unexpected.map(warning => `${warning.location?.file ?? '?'}: ${warning.text}`).join('\n')}`);
  }
  const bundle = result.outputFiles[0].text;
  const [output] = Object.values(result.metafile.outputs);
  const modules = await Promise.all(Object.keys(result.metafile.inputs).sort().map(async input => {
    const bytes_in_bundle = output.inputs[input]?.bytesInOutput ?? 0;
    if (input === 'mml-native:canonical-bootstrap') {
      return { path: 'studio/backend/bootstrap/index.mjs', replaced_by: 'canonical-runtime-package', sha256: sha256(runtimePackage.bootstrapModule), bytes_in_bundle };
    }
    if (input === 'mml-native:build') return { path: 'mml-native:build', generated: true, sha256: null, bytes_in_bundle };
    return { path: input, sha256: sha256(await readFile(resolve(root, input))), bytes_in_bundle };
  }));
  const manifest = {
    format: NATIVE_CORE_MANIFEST_FORMAT,
    api_version: 1,
    bundle: { path: NATIVE_CORE_FILES.bundle, sha256: sha256(bundle), bytes: Buffer.byteLength(bundle) },
    release: { canonical: runtimePackage.metadata, runtime_package_digest: runtimePackage.digest },
    toolchain: { bundler: `esbuild@${esbuildVersion}`, format: 'iife', target: NATIVE_CORE_TARGET },
    modules,
    audit: {
      note: 'Dynamic Git and build provenance. Audit only: excluded from the bundle and from its SHA-256, and not re-verified by a host.',
      ...runtimePackage.provenance,
    },
  };
  return { bundle, manifest, runtimePackage };
}

// The Node server path's answer to every conformance case, in the envelope the
// native facade returns. It is composed exactly as server/mcp.mjs composes the
// technical tools, with the native service version so a whole report compares.
export async function answerConformanceCases(cases = NATIVE_CONFORMANCE_CASES) {
  const [{ createTechnicalService }, { createCanonicalGate }, { NATIVE_SERVICE_VERSION }] = await Promise.all([
    import('../studio/backend/application/technical-service.mjs'),
    import('../studio/backend/application/provenance.mjs'),
    import('../studio/native/core-facade.mjs'),
  ]);
  const technical = createTechnicalService({ serviceVersion: NATIVE_SERVICE_VERSION, canonical: createCanonicalGate() });
  const answers = [];
  for (const { name, operation, request } of cases) {
    let expected;
    try {
      expected = { ok: true, result: await technical[operation](structuredClone(request)) };
    } catch (error) {
      if (error?.name !== 'StudioApplicationError') throw error;
      expected = { ok: false, error: { code: error.code, message: error.message, details: error.details ?? {} } };
    }
    answers.push({ name, operation, request, expected: JSON.parse(JSON.stringify(expected)) });
  }
  return answers;
}

export async function buildNativeCore({ root = repositoryRoot, out = resolve(root, 'studio/native-build'), prHead = null, write = true } = {}) {
  // Fail before producing any output if published discovery/history is missing.
  const canonical = loadPublishedCanonical({ root, prHead, supportedCanonicalVersion: SUPPORTED_CANONICAL_VERSIONS });
  const { bundle, manifest, runtimePackage } = await buildNativeCoreBundle({ root, canonical });
  const conformance = {
    format: NATIVE_CORE_CONFORMANCE_FORMAT,
    canonical: runtimePackage.metadata,
    runtime_package_digest: runtimePackage.digest,
    bundle_sha256: manifest.bundle.sha256,
    cases: await answerConformanceCases(),
  };
  if (write) {
    await rm(out, { recursive: true, force: true });
    await mkdir(out, { recursive: true });
    await writeFile(resolve(out, NATIVE_CORE_FILES.bundle), bundle);
    await writeFile(resolve(out, NATIVE_CORE_FILES.manifest), `${JSON.stringify(manifest, null, 2)}\n`);
    await writeFile(resolve(out, NATIVE_CORE_FILES.conformance), `${JSON.stringify(conformance, null, 2)}\n`);
  }
  return { bundle, manifest, conformance };
}

// The entry module is compared by real path on both sides: Node takes
// import.meta.url from the entry's real path (or from the link itself under
// --preserve-symlinks-main), while argv[1] is the path the caller typed, so a
// script started through a symlink would otherwise do nothing and exit 0.
const invokedAsScript = (() => {
  try { return Boolean(process.argv[1]) && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url)); } catch { return false; }
})();
if (invokedAsScript) {
  const args = process.argv.slice(2);
  if (args.includes('--help')) {
    console.log('Usage: node scripts/build-native-core.mjs [--out=<dir>]\nBuilds studio/native-build/{mml-core.js,mml-core.json,conformance.json} for native hosts (apps/ios). Needs the published main history (see docs/CANONICAL_MANIFEST.md).');
  } else {
    const outArg = args.find(arg => arg.startsWith('--out='));
    const out = resolve(repositoryRoot, outArg ? outArg.slice('--out='.length) : (process.env.NATIVE_CORE_BUILD_OUT ?? 'studio/native-build'));
    const prHead = process.env.GITHUB_EVENT_NAME === 'pull_request'
      ? JSON.parse(await readFile(process.env.GITHUB_EVENT_PATH, 'utf8')).pull_request.head.sha : null;
    const { manifest, conformance } = await buildNativeCore({ out, prHead });
    console.log(JSON.stringify({
      output: out,
      bundle: manifest.bundle,
      canonical: manifest.release.canonical,
      runtime_package_digest: manifest.release.runtime_package_digest,
      modules: manifest.modules.length,
      conformance_cases: conformance.cases.length,
      audit: manifest.audit,
    }));
  }
}
