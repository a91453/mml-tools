test('an incomplete Raw MIDI project stays incomplete through a merge, whatever the caller claims', () => {
  const damaged = asset('truncated.mid', fixtures.truncatedTrack());
  assert.equal(damaged.project.metadata.sourceComplete, false);

  const merged = mergeCanonicalProjects([damaged.project], {
    id: 'merged',
    // PR #20: caller metadata is annotation and is spread first; what the merge
    // computed is written after it and is not overridable.
    metadata: { sourceComplete: true, incompleteInputs: [], componentProjects: [] },
  });
  assert.equal(merged.metadata.sourceComplete, false);
  assert.deepEqual(merged.metadata.incompleteInputs, [damaged.project.id]);
  assert.equal(merged.metadata.componentProjects.length, 1);
});

test('a tampered persisted record cannot claim a source identity it does not have', () => {
  const result = asset('zero.mid', fixtures.format0());
  for (const [mutate, reason] of [
    [record => { record.source.sha256 = '0'.repeat(64); }, 'SOURCE_DIGEST_MISMATCH'],
    [record => { record.source.byteLength = 3; }, 'SOURCE_BYTE_LENGTH_MISMATCH'],
    [record => { record.project.sources[0].sha256 = '1'.repeat(64); }, 'CANONICAL_SOURCE_DIGEST_MISMATCH'],
    [record => { record.source.bytesBase64 = encodeSourceBytes(fixtures.format1()); }, 'SOURCE_DIGEST_MISMATCH'],
    [record => { delete record.source.bytesBase64; }, 'SOURCE_BYTES_MISSING'],
  ]) {
    const record = structuredClone(result);
    mutate(record);
    const verdict = verifySourceBytes(record);
    assert.equal(verdict.verified, false);
    assert.ok(verdict.reasons.includes(reason), `${reason} must be reported, got ${verdict.reasons.join(',')}`);
  }
});

