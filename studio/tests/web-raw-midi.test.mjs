// Studio Web Raw MIDI transport.
//
// The backend suites already prove what `ingestMIDI` decodes. What is unproven
// until here is that the browser path reaches that decoder with the exact bytes
// the user chose, that nothing between the file picker and the Canonical
// project reinterprets them, and that what is written to storage decodes back
// to the same sequence. Every fixture is synthetic and generated by this
// repository.

const asset = (name, bytes, options = {}) => intakeMidi({ name, bytes, id: options.id ?? 'web-midi', authority: options.authority });
const nodeDigest = bytes => createHash('sha256').update(Buffer.from(bytes)).digest('hex');

// ─── byte-exact transport ───────────────────────────────────────────────────

test('the persistence encoding is byte-exact for every byte value', () => {
  const every = new Uint8Array(256).map((_, index) => index);
  assert.deepEqual([...decodeSourceBytes(encodeSourceBytes(every))], [...every]);

  // Lengths around the base64 padding boundaries, plus a body of arbitrary
  // bytes: a UTF-8 round trip would replace the invalid sequences in here.
  for (const length of [0, 1, 2, 3, 4, 5, 255, 1024, 4097]) {
    const bytes = new Uint8Array(length).map((_, index) => (index * 97 + 13) & 0xff);
    const back = decodeSourceBytes(encodeSourceBytes(bytes));
    assert.deepEqual([...back], [...bytes], `length ${length} must survive`);
    assert.equal(nodeDigest(back), nodeDigest(bytes));
  }
});

test('a malformed persistence encoding is refused rather than silently repaired', () => {
  for (const bad of ['not base64!', 'TVRoZA', 'TVRo ZA==', null, undefined, 42]) {
    assert.throws(() => decodeSourceBytes(bad), /SOURCE_BYTES_UNREADABLE/);
  }
});

test('the source digest is taken over exactly the bytes that were parsed', () => {
  const bytes = fixtures.format1();
  const result = asset('format1.mid', bytes);
  assert.equal(result.source.sha256, nodeDigest(bytes));
  assert.equal(result.source.byteLength, bytes.length);
  assert.equal(result.project.sources[0].sha256, result.source.sha256);
  assert.deepEqual([...decodeSourceBytes(result.source.bytesBase64)], [...bytes]);
  assert.equal(verifySourceBytes(result).verified, true);
});

test('an ArrayBuffer and a subarray view over the same bytes ingest identically', () => {
  const bytes = fixtures.format0();
  const padded = new Uint8Array(bytes.length + 8);
  padded.set(bytes, 8);
  const view = padded.subarray(8);

  const buffer = bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength);
  const fromBuffer = asset('a.mid', buffer);
  const fromView = asset('a.mid', view);

  assert.equal(fromBuffer.source.sha256, nodeDigest(bytes));
  assert.equal(fromView.source.sha256, fromBuffer.source.sha256);
  assert.equal(JSON.stringify(fromView.project), JSON.stringify(fromBuffer.project));
  // Structured clone is the Worker boundary's copy semantics: the page's own
  // buffer is never transferred, so it is still readable afterwards.
  assert.equal(buffer.byteLength, bytes.length, 'the page copy must not be detached');
});

test('a Worker round trip preserves the asset and its exact rational timing', () => {
  const result = asset('rational.mid', fixtures.rationalTiming());
  const starts = result.project.events.map(event => event.start);
  // 0, 1/3, 2/3, 1, 13/12, 29/24 -- values no float projection reproduces.
  assert.deepEqual(starts, ['0', '1/3', '2/3', '1', '13/12', '29/24']);
  assert.deepEqual(result.project.events.map(event => event.end), ['1/3', '2/3', '1', '13/12', '29/24', '2']);

  for (const transported of [structuredClone(result), JSON.parse(JSON.stringify(result))]) {
    assert.deepEqual(transported.project.events.map(event => event.start), starts);
    assert.equal(transported.source.sha256, result.source.sha256);
    assert.equal(verifySourceBytes(transported).verified, true);
    // Exact rationals, not decimal approximations of them.
    assert.equal(f(transported.project.events[1].start).cmp(f('1/3')), 0);
    assert.equal(f(transported.project.events[5].start).cmp(f('29/24')), 0);
  }
});

