// ─── request identity ───────────────────────────────────────────────────────

test('only the newest request for a slot may become the active source', () => {
  const ledger = createSourceRequestLedger();
  const a = ledger.begin('candidate', { projectId: 'p1', revision: 0 });
  const b = ledger.begin('candidate', { projectId: 'p1', revision: 0 });

  // A returns late; B is what the user last chose.
  assert.deepEqual(ledger.evaluate(a, { projectId: 'p1' }), { accepted: false, reason: STALE_SOURCE_REQUEST });
  assert.deepEqual(ledger.evaluate(b, { projectId: 'p1' }), { accepted: true, reason: null });

  // Identical filenames are not identity: two requests are two requests.
  assert.notEqual(a.sequence, b.sequence);

  // Another slot is unaffected by the candidate slot's traffic.
  const other = ledger.begin('baseline', { projectId: 'p1' });
  assert.equal(ledger.evaluate(other, { projectId: 'p1' }).accepted, true);

  // Navigating to another project discards results requested against the old one.
  assert.deepEqual(ledger.evaluate(b, { projectId: 'p2' }), { accepted: false, reason: SOURCE_REQUEST_PROJECT_CHANGED });

  ledger.settle(b);
  assert.deepEqual(ledger.evaluate(b, { projectId: 'p1' }), { accepted: false, reason: STALE_SOURCE_REQUEST });
});

test('an intake stays valid across revisions of the same project', () => {
  const ledger = createSourceRequestLedger();
  const token = ledger.begin('candidate', { projectId: 'p1', revision: 3 });
  // The workspace revision moved while the decode was in flight; the captured
  // bytes are still the user's choice and still invalidate on their own.
  assert.equal(ledger.evaluate(token, { projectId: 'p1' }).accepted, true);
  assert.deepEqual(ledger.inFlight, [{ slot: 'candidate', sequence: token.sequence, projectId: 'p1', revision: 3 }]);
});

