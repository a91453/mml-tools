test('a portable backup carries the MIDI bytes and re-ingests from them', () => {
  const workspace = newWorkspace();
  workspace.assets.candidate = asset('backup.mid', fixtures.format1(), { id: 'original' });
  const backup = JSON.stringify(workspace);
  const restored = importWorkspace(backup);

  const before = workspace.assets.candidate;
  const after = restored.assets.candidate;
  assert.equal(after.format, MIDI_SOURCE_FORMAT);
  assert.equal(after.source.sha256, before.source.sha256);
  assert.deepEqual([...decodeSourceBytes(after.source.bytesBase64)], [...fixtures.format1()]);
  assert.equal(after.project.events.length, before.project.events.length);
  assert.equal(verifySourceBytes(after).verified, true);

  // A backup whose bytes and claimed identity disagree is refused outright.
  const tampered = JSON.parse(backup);
  tampered.assets.candidate.source.bytesBase64 = encodeSourceBytes(fixtures.format0());
  assert.throws(() => importWorkspace(JSON.stringify(tampered)), /SOURCE_DIGEST_MISMATCH/);

  // And one whose project was edited is rebuilt from the bytes regardless.
  const edited = JSON.parse(backup);
  edited.assets.candidate.project.events = [];
  edited.assets.candidate.complete = true;
  const rebuilt = importWorkspace(JSON.stringify(edited));
  assert.equal(rebuilt.assets.candidate.project.events.length, before.project.events.length);
});

test('changing the source clears every review the old bytes were judged under', () => {
  let workspace = { ...newWorkspace(), title: 'fixture', settings: { meterText: '0 4/4', recording: 'synthetic', offset: '0', end: '2', audioRequired: 'no', preview: 'none' } };
  workspace.assets.candidate = asset('same-name.mid', fixtures.format0(), { id: 'first' });
  workspace = recordReview(workspace, 'source', 'checked', 'synthetic');
  assert.equal(workspace.reviews.source.revision, workspace.revision);

  const next = invalidate(workspace);
  // Same filename, different bytes: a new source revision, not the old one.
  next.assets.candidate = asset('same-name.mid', fixtures.format1(), { id: 'second' });
  assert.notEqual(next.assets.candidate.source.sha256, workspace.assets.candidate.source.sha256);
  assert.equal(next.revision, workspace.revision + 1);
  assert.deepEqual(next.reviews, {});
});
