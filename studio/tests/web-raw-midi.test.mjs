test('caller metadata cannot raise a backend completeness verdict', () => {
  const damaged = asset('truncated.mid', fixtures.truncatedTrack());
  assert.equal(damaged.complete, false);

  // Whatever a restored or imported record claims, the analysis reads the
  // evidence, not the claim.
  const laundered = structuredClone(damaged);
  laundered.complete = true;
  laundered.unsupported = [];
  laundered.project.metadata.sourceComplete = true;

  let workspace = { ...newWorkspace(), title: 'fixture', settings: { meterText: '0 4/4', recording: 'synthetic', offset: '0', end: '2', audioRequired: 'no', preview: 'none' } };
  workspace.assets.candidate = laundered;
  workspace.assets.baseline = laundered;
  for (const name of REVIEW_NAMES) workspace = recordReview(workspace, name, 'reviewed', 'synthetic');

  const report = analyzeWorkspace(workspace);
  const entry = report.rawMidi[0];
  assert.equal(entry.claimedComplete, true, 'the record still says what it says');
  assert.equal(entry.complete, false, 'but the verdict comes from re-reading the bytes');
  assert.equal(entry.integrity.verified, false);
  assert.ok(entry.integrity.reasons.includes('STORED_COMPLETENESS_DOES_NOT_MATCH_SOURCE_BYTES'));
  assert.ok(entry.integrity.reasons.includes('STORED_UNSUPPORTED_EVIDENCE_DOES_NOT_MATCH_SOURCE_BYTES'));
  assert.equal(entry.unsupported.some(item => item.code === 'TRACK_TRUNCATED'), true, 'the erased evidence is restored to the report');

  assert.equal(report.gates.rawMidiSource.status, 'UNSUPPORTED');
  assert.equal(report.gates.source.status, 'UNSUPPORTED', 'a recorded source review cannot stand in for the erased evidence');
  assert.ok(report.blockers.includes('rawMidiSource'));
  assert.notEqual(report.state, 'VALIDATED');
});

