// A tiny synthetic SF2 bank for prescreen tests. Deterministic, generated in
// memory with spessasynth_core's own writer, never downloaded and never
// stored: every GM program and drum note the game-instrument table uses, each
// a one-period harmonic loop (or a short drum hit) with an envelope that makes
// its kind of instrument recognisable (plucked voices decay while held, the
// harp rings for seconds after its release, bowed and blown voices sustain).
import { createHash } from 'node:crypto';
import { BasicInstrument, BasicPreset, BasicSoundBank, EmptySample, Generator, GeneratorTypes } from 'spessasynth_core';
import { GM_DRUM_NOTES, GM_PROGRAMS } from '../../backend/audio/instruments.mjs';

const RATE = 44000;
const timecents = seconds => Math.round(1200 * Math.log2(seconds));

// One period of a band-limited sawtooth-like wave at A4 (440 Hz = 100 samples
// at 44 kHz), eight harmonics at 1/k.
function harmonicPeriod() {
  const data = new Float32Array(100);
  for (let i = 0; i < 100; i++) {
    let v = 0;
    for (let k = 1; k <= 8; k++) v += Math.sin((2 * Math.PI * k * i) / 100) / k;
    data[i] = 0.45 * v;
  }
  return data;
}

function drumHit(kind) {
  const length = Math.round(RATE * 0.6);
  const data = new Float32Array(length);
  let seed = kind === 'kick' ? 12345 : 67890;
  for (let i = 0; i < length; i++) {
    const t = i / RATE;
    if (kind === 'kick') data[i] = 0.8 * Math.sin(2 * Math.PI * 60 * t) * Math.exp(-t / 0.12);
    else {
      seed = (seed * 1103515245 + 12345) >>> 0;
      data[i] = 0.5 * ((seed / 2 ** 32) * 2 - 1) * Math.exp(-t / 0.25);
    }
  }
  return data;
}

// program → [held decay seconds to silence (null = sustain), release seconds]
const ENVELOPES = new Map([
  [0, [3, 0.3]], [10, [2, 0.4]], [13, [0.8, 0.2]], [24, [2.5, 0.25]], [25, [2, 0.25]],
  [46, [4, 3.0]], [40, [null, 0.12]], [71, [null, 0.1]], [73, [null, 0.1]],
]);

export function syntheticSoundBank() {
  const bank = new BasicSoundBank();
  const tone = new EmptySample();
  tone.name = 'Harmonic A4';
  tone.originalKey = 69;
  tone.pitchCorrection = 0;
  tone.setAudioData(harmonicPeriod(), RATE);
  tone.loopStart = 0;
  tone.loopEnd = 100;
  bank.addSamples(tone);

  for (const program of GM_PROGRAMS) {
    const [decay, release] = ENVELOPES.get(program) ?? [null, 0.1];
    const instrument = new BasicInstrument();
    instrument.name = `Synthetic ${program}`;
    const generators = [new Generator(GeneratorTypes.sampleModes, 1), new Generator(GeneratorTypes.releaseVolEnv, timecents(release))];
    if (decay !== null) generators.push(new Generator(GeneratorTypes.decayVolEnv, timecents(decay)), new Generator(GeneratorTypes.sustainVolEnv, 1000));
    instrument.globalZone.addGenerators(...generators);
    instrument.createZone(tone);
    bank.addInstruments(instrument);
    const preset = new BasicPreset(bank);
    preset.name = `Synthetic ${program}`;
    preset.program = program;
    preset.bankMSB = 0;
    preset.createZone(instrument);
    bank.addPresets(preset);
  }

  const kit = new BasicInstrument();
  kit.name = 'Synthetic kit';
  for (const note of GM_DRUM_NOTES) {
    const hit = new EmptySample();
    hit.name = `Drum ${note}`;
    hit.originalKey = note;
    hit.pitchCorrection = 0;
    hit.setAudioData(drumHit(note < 40 ? 'kick' : 'cymbal'), RATE);
    bank.addSamples(hit);
    const zone = kit.createZone(hit);
    zone.keyRange = { min: note, max: note };
    zone.setGenerator(GeneratorTypes.releaseVolEnv, timecents(note < 40 ? 0.2 : 1.5));
  }
  bank.addInstruments(kit);
  const drums = new BasicPreset(bank);
  drums.name = 'Synthetic kit';
  drums.program = 0;
  drums.bankMSB = 128;
  drums.isGMGSDrum = true;
  drums.createZone(kit);
  bank.addPresets(drums);

  bank.soundBankInfo.name = 'Synthetic prescreen test bank';
  bank.flush();
  const bytes = new Uint8Array(bank.writeSF2());
  return {
    bytes,
    descriptor: Object.freeze({
      id: 'synthetic-test-bank',
      name: 'Synthetic prescreen test bank',
      url: null,
      sha256: createHash('sha256').update(bytes).digest('hex'),
      bytes: bytes.byteLength,
      format: 'sf2',
      license: 'generated by the test suite',
      label: 'synthetic test bank',
    }),
  };
}
